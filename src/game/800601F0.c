ULONG Snd_tone_mask(VagAtr *pVag, SND_TRACK *pTr, UCHAR tones)
{
    ULONG i;
    ULONG mask;

    mask = 0;
    for (i = 0; i < tones; i++, pVag++) {
        if (pTr->Note >= pVag->min && pVag->max >= pTr->Note) {
            mask |= 1 << i;
        }
    }
    return mask;
}

