void Snd_seq_fade_in(SND_SEQ *pSeq)
{
    if (pSeq->Unk2C != 0) {
        if (pSeq->Unk3C >= 0x3FFF - pSeq->Unk40) {
            pSeq->Unk3C = 0x3FFF;
            pSeq->Unk38 = 0;
        } else {
            pSeq->Unk3C += pSeq->Unk40;
        }
    }
}

void Snd_seq_fade_out(SND_SEQ *pSeq)
{
    if (pSeq->Unk2C != 0) {
        if (pSeq->Unk3C <= pSeq->Unk40) {
            pSeq->Unk3C = 0;
            pSeq->Unk38 = 0;
        pSeq->Unk2D = 1;
            pSeq->Unk2D = 1;
        } else {
            pSeq->Unk3C -= pSeq->Unk40;
        }
    }
}

