void Rot_add_matrix(LONG *pPos, SHORT *pDir, MATRIX *pM, SVECTOR *Add_dir)
{
    MATRIX Mat;
    MATRIX Mat2;
    SVECTOR Svec;
    VECTOR Vec;
    LONG ang;
    int m02;
    int m12;

    int ySq;
    int x;
    int y;

    Mat.t[0] = pPos[0];
    Mat.t[1] = pPos[1];
    Mat.t[2] = pPos[2];
    RotMatrix(Add_dir, &Mat);
    MulMatrix2(&Mat, pM);
    MatrixNormal(pM, pM);

    m02 = pM->m[0][2];
    m12 = pM->m[1][2];
    x = pM->m[2][2];
    y = m02 * m02;
    y += m12 * m12;
    y += x * x;
    y = (m02 << 0xc) / (y / 4096);

    ang = ratan2(-m12, x);
    *pDir = ang;

    ySq = y * y;
    if (ySq < 0) {
        ySq += 0xfff;
    }
    ang = SquareRoot12(0x1000 - (ySq >> 0xc));
    ang = ratan2(y, ang);
    pDir[1] = ang;
    pDir[2] = 0;

    Mat.t[0] = 0;
    Mat.t[1] = 0;
    Mat.t[2] = 0;
    RotMatrix((SVECTOR *)pDir, &Mat);
    TransposeMatrix(&Mat, &Mat2);

    Svec.vx = pM->m[0][0];
    Svec.vy = pM->m[1][0];
    Svec.vz = pM->m[2][0];
    ApplyMatrix(&Mat2, &Svec, &Vec);
    ang = ratan2(Vec.vy, Vec.vx);
    pDir[2] = ang;
}

