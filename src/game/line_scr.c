void Scr_effect(void)
{
    LINE_SCR *pLine;
    ULONG Amp;

    pLine = &Line;
    if (!(G.Status_flg & 7)) {
        Line.r_no_0 = 0;
        return;
    }
    if (Line.r_no_0 == 0) {
        pLine->Rect.x = 0;
        pLine->Rect.w = 320;
        pLine->Rect.y = 0;
        pLine->Unk2D20[0] = 0;
        pLine->Rect.h = 240;
        pLine->Unk2D20[1] = 0;
        pLine->Unk2D20[2] = 0;
        pLine->Unk2D20[3] = 2;
        pLine->Unk2D20[4] = 0x40;
        pLine->Unk2D20[5] = 2;
        Line.r_no_0++;
    }
    if (G.Status_flg & 4) {
        line_mode_set(0, 7);
        Amp = 1;
    } else if (G.Status_flg & 2) {
        line_mode_set(0, 7);
        Amp = 2;
    } else {
        return;
    }
    Scr_quake(Amp);
    line_scr_end();
}

